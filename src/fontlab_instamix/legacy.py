# this_file: src/fontlab_instamix/legacy.py
"""Remove what a legacy ``install.vfpy`` created before instamix takes over.

The legacy installers log every created path in
``Extensions/<id>/install.log`` (JSON lines). Only paths that the log lists
*and* that are provably the installer's are removed: links that point
where the log (or the package) says, folders holding the installer's
marker or ``INSTALLER == install.vfpy``, and script files whose SHA-256
matches the logged hash or, for logs without hashes, a file instamix is
about to install. Everything else is kept and reported. The log itself
stays as history, with an ``uninstall`` record appended.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import time
from pathlib import Path

from . import env, ledger

MARKER = ".fontlab-install.json"
MODULE = "fontlab_install"
MENU = "Scripts/Extensions"
LEGACY_INSTALLER = "install.vfpy\n"
LAUNCHER = "#FLM: %s\n# Generated by install.vfpy; replaced on every install.\nimport fontlab_install\nfontlab_install.%s\n"


def log_path(data: Path, ext_id: str) -> Path:
    return Path(data) / "Extensions" / ext_id / "install.log"


def last_state(path: Path) -> dict | None:
    """The newest install/uninstall record in a legacy log, if any."""
    state = None
    if path.is_file():
        for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
            try:
                record = json.loads(line)
            except ValueError:
                continue
            if isinstance(record, dict) and record.get("action") in ("install", "uninstall"):
                state = record
    return state


def installed(data: Path, ext_id: str) -> dict | None:
    """The legacy install record of *ext_id*, if a legacy install is active."""
    state = last_state(log_path(data, ext_id))
    return state if state and state.get("action") == "install" else None


def active_ids(data: Path) -> list[str]:
    """Ids with an active legacy install."""
    root = Path(data) / "Extensions"
    logs = sorted(root.glob("*/install.log")) if root.is_dir() else []
    return [log.parent.name for log in logs if (last_state(log) or {}).get("action") == "install"]


def _inside(data: Path, path: Path) -> bool:
    base = os.path.realpath(data)
    return os.path.realpath(path.parent).startswith(base + os.sep) or os.path.realpath(path.parent) == base


def _points_into(link: Path, roots: list) -> bool:
    target = os.path.realpath(link)
    for root in roots:
        base = os.path.realpath(root) if root else None
        if base and (target == base or target.startswith(base + os.sep)):
            return True
    return False


def owns_folder(path: Path, state: dict) -> bool:
    """True for the legacy lib/ (marker with our id) or a legacy dist-info."""
    try:
        marker = path / MARKER
        if marker.is_file() and not marker.is_symlink():
            return json.loads(marker.read_text(encoding="utf-8")).get("id") == state.get("id")
        installer = path / "INSTALLER"
        return path.name.endswith(".dist-info") and installer.is_file() and installer.read_text(
            encoding="utf-8"
        ) == LEGACY_INSTALLER
    except (OSError, ValueError, AttributeError):
        return False


def _uninstaller_text(ext_id: str) -> str:
    return LAUNCHER % ("Uninstall " + ext_id, f"uninstall({ext_id!r})")


def _check(path: Path, data: Path, state: dict, known: set[str]) -> str | None:
    """Why *path* must be kept, or None when it is provably the legacy installer's."""
    scripts = os.path.realpath(Path(data) / "Scripts")
    in_scripts = os.path.realpath(path).startswith(scripts + os.sep)
    if path.is_symlink():
        links = state.get("links")
        if links:
            return None if links.get(str(path)) == os.readlink(path) else "link not recorded as ours or changed"
        roots = [Path(data) / "Extensions" / str(state.get("id")) / "lib", state.get("source")]
        return None if _points_into(path, roots) else "link not recorded as ours or changed"
    if path.is_dir():
        if in_scripts:
            return None if not any(path.iterdir()) else "folder is not empty"
        return None if owns_folder(path, state) else "folder not proven ours (no installer marker)"
    if not in_scripts:
        return "file not proven ours"
    digest, hashes = ledger.sha256(path), state.get("hashes") or {}
    if str(path) in hashes:
        return None if hashes[str(path)] == digest else "edited since install"
    return None if digest in known else "no logged hash and differs from the new install"


def plan(data: Path, state: dict, known: set[str]) -> tuple[list[Path], list[tuple[str, str]]]:
    """(paths to remove, [(path, reason)] to keep) for a legacy install record."""
    remove, kept = [], []
    known = known | {ledger_text_hash(_uninstaller_text(str(state.get("id"))))}
    for raw in state.get("files", []):
        path = Path(raw)
        if not path.is_absolute():
            path = Path(data) / raw
        if not (path.is_symlink() or path.exists()):
            continue
        if not _inside(data, path):
            kept.append((str(path), "outside FontLab's data folder"))
            continue
        reason = _check(path, data, state, known)
        if reason:
            kept.append((str(path), reason))
        else:
            remove.append(path)
    return remove, kept


def ledger_text_hash(text: str) -> str:
    """SHA-256 of generated text, as :func:`ledger.sha256` hashes the written file."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _remove(path: Path, data: Path) -> None:
    if path.is_symlink() or path.is_file():
        path.unlink()
        if path.suffix in (".py", ".vfpy"):
            for compiled in (path.with_suffix(".pyc"), path.with_suffix(".vfpyc")):
                if compiled.is_file() and not compiled.is_symlink():
                    compiled.unlink()
    elif path.is_dir():
        if not any(path.iterdir()):
            path.rmdir()
        else:
            shutil.rmtree(path)
    _prune(path.parent, Path(data) / "Scripts")


def _prune(folder: Path, scripts: Path) -> None:
    while folder != scripts and scripts in folder.parents:
        try:
            folder.rmdir()
        except OSError:
            return
        folder = folder.parent


def migrate(data: Path, ext_id: str, known: set[str], targets: set[str]) -> dict | None:
    """Remove the legacy install of *ext_id*; return a summary, or None if none exists.

    *known* holds SHA-256 digests of files instamix will install; *targets*
    holds data-relative POSIX paths it will create. A kept legacy file at
    one of those targets would block the new install, so nothing is
    removed and :class:`MigrationError` lists the conflicts.
    """
    data = Path(data)
    state = installed(data, ext_id)
    if not state:
        return None
    remove, kept = plan(data, state, known)
    blocked = [path for path, _ in kept if _rel(data, path) in targets]
    if blocked:
        raise MigrationError(f"legacy files of {ext_id} changed since install and block it: " + ", ".join(blocked))
    for path in sorted(remove, key=lambda p: len(p.parts), reverse=True):
        if path.is_symlink() or path.exists():
            _remove(path, data)
    record = {"action": "uninstall", "id": ext_id, "time": time.strftime("%Y-%m-%dT%H:%M:%S"), "migrated_to": "fontlab-instamix"}
    record["kept"] = [path for path, _ in kept]
    with log_path(data, ext_id).open("a", encoding="utf-8") as stream:
        stream.write(json.dumps(record, sort_keys=True) + "\n")
    cleanup_shared(data)
    return {"id": ext_id, "removed": [str(p) for p in remove], "kept": kept}


def _rel(data: Path, path: str) -> str:
    try:
        return Path(path).relative_to(data).as_posix()
    except ValueError:
        return path


def cleanup_shared(data: Path) -> list[Path]:
    """Remove the shared legacy tools once no legacy install remains."""
    data = Path(data)
    if active_ids(data):
        return []
    menu = data / MENU
    candidates = [
        (env.site_packages(data) / (MODULE + ".py"), None),
        (menu / "List Extensions.py", LAUNCHER % ("List Extensions", "list_extensions()")),
        (menu / MARKER, json.dumps({"id": MODULE}) + "\n"),
    ]
    removed = []
    for path, expected in candidates:
        if not path.is_file() or path.is_symlink():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if (expected is None and 'MODULE = "fontlab_install"' in text) or text == expected:
            path.unlink()
            removed.append(path)
    try:
        menu.rmdir()
    except OSError:
        pass
    return removed


class MigrationError(RuntimeError):
    """A legacy install cannot be replaced without losing changed files."""
